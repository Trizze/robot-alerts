import { readFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { SharedStore } from './store.js';
import { createService } from './server.js';
import { twitchClient } from './twitch.js';
import { serviceUrls } from './urls.js';

const required = name => { const value = process.env[name]; if (!value) throw new Error(`Missing ${name}`); return value; };
const key = name => { const value = Buffer.from(required(name),'base64'); if (value.length !== 32) throw new Error(`${name} must be 32 random bytes encoded as base64`); return value; };
const {callback, webhookCallback, frontendUrl} = serviceUrls(required('PUBLIC_BASE_URL'),required('FRONTEND_URL'));
const webhookSecret = required('TWITCH_WEBHOOK_SECRET');
if (webhookSecret.length < 10 || webhookSecret.length > 100) throw new Error('TWITCH_WEBHOOK_SECRET must be 10–100 characters');
const catalog = JSON.parse(readFileSync(new URL('../../website-staging/patterns/catalog.json',import.meta.url))).patterns;
const dataPath = process.env.DATA_PATH || '/data/robot-alerts.sqlite'; mkdirSync(dirname(dataPath),{recursive:true});
const store = new SharedStore(dataPath,{encryptionKey:key('DATA_ENCRYPTION_KEY'),patternSeed:key('PATTERN_SEED'),catalog});
const twitch = twitchClient({clientId:required('TWITCH_CLIENT_ID'),clientSecret:required('TWITCH_CLIENT_SECRET'),callback,webhookCallback,webhookSecret});
const port = Number(process.env.PORT || 8080); if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error('Invalid PORT');
const server = createService({store,twitch,webhookSecret,frontendUrl});
server.listen(port,'0.0.0.0',()=>console.log(`Robot Alerts service listening on port ${port}`));
for (const signal of ['SIGINT','SIGTERM']) process.on(signal,()=>server.close(()=>{ store.close(); process.exit(0); }));
